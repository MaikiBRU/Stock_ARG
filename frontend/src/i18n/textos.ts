/** Diccionario del idioma pedido, con español como respaldo. */
export function textosDe(idioma: string | undefined): Textos {
  return idioma === "en" ? en : es;
}

/** Reemplaza {clave} por su valor: "Página {p}" pasa a "Página 2". */
export function formatear(
  texto: string,
  valores: Record<string, string | number>,
) {
  return texto.replace(/\{(\w+)\}/g, (entero, clave: string) =>
    clave in valores ? String(valores[clave]) : entero,
  );
}
